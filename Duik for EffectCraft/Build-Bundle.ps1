$ErrorActionPreference = 'Stop'
$source = Join-Path $PSScriptRoot 'src'
$bundle = Join-Path $PSScriptRoot 'plug-in'
$name = 'Duik for EffectCraft.jsx'
$entry = [IO.File]::ReadAllText((Join-Path $source $name))
$compiled = [regex]::Replace($entry, '(?m)^    #include "([A-Za-z]+\.jsxinc)"\r?$', {
    param($include)
    $file = $include.Groups[1].Value
    $content = [IO.File]::ReadAllText((Join-Path $source $file)).TrimEnd()
    return "    // $file`n" + [regex]::Replace($content, '(?m)^(?=\S| )', '    ')
})
$null = New-Item -ItemType Directory -Path $bundle -Force
$output = Join-Path $bundle $name
[IO.File]::WriteAllText($output, "// Generated by Build-Bundle.ps1. Edit files in src/.`n" + $compiled.Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output $output
